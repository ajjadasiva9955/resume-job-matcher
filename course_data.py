# Course lookup helpers
_COURSES_BY_ID = {c["id"]: c for c in COURSES_DATA}
_COURSES_BY_SLUG = {c["slug"]: c for c in COURSES_DATA}

def get_all_courses():
    """Returns the complete list of 9 courses."""
    return COURSES_DATA

def get_course_by_id(identifier):
    """Looks up course by id or slug."""
    if not identifier:
        return None
    ident = str(identifier).strip().lower()
    return _COURSES_BY_ID.get(ident) or _COURSES_BY_SLUG.get(ident)

def get_course_topics(course_id):
    """Returns the list of topics for a course."""
    course = get_course_by_id(course_id)
    if not course:
        return []
    return course.get("topics", [])

def get_topic_by_id(course_id, topic_id):
    """Returns a specific topic dictionary within a course."""
    topics = get_course_topics(course_id)
    t_id = str(topic_id).strip().lower()
    for topic in topics:
        if str(topic.get("id")).lower() == t_id or str(topic.get("order")) == t_id:
            return topic
    return None
