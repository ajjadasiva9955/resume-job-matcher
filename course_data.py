import re

def extract_youtube_video_id(url):
    """Safely extracts the 11-character YouTube video ID from various URL formats."""
    if not url:
        return ""
    match = re.search(r"(?:v=|\/embed\/|youtu\.be\/|\/v\/)([a-zA-Z0-9_-]{11})", url)
    if match:
        return match.group(1)
    return ""

def extract_youtube_start_time(url):
    """Extracts start time in seconds from YouTube URL if present (e.g. t=17s, t=355s, t=20s)."""
    if not url:
        return ""
    match = re.search(r"[?&]t=(\d+)s?", url)
    if match:
        return match.group(1)
    return ""


